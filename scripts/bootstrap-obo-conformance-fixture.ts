/**
 * scripts/bootstrap-obo-conformance-fixture.ts
 *
 * Deterministic, idempotent, test-only OBO conformance fixture seed tool.
 *
 * Reads secrets from a temporary secret bundle (JSON, mode 600), reads the
 * frozen V1 audience definitions from the generated runtime contract, and
 * creates the minimal set of database records needed to exercise the real
 * OBO Token Exchange (RFC 8693) pipeline.
 *
 * Usage:
 *   export DATABASE_URL=postgresql://...
 *   tsx scripts/bootstrap-obo-conformance-fixture.ts \
 *     --secret-bundle /path/to/.secrets.obo.json
 *
 *   # Print manifest without writing:
 *   tsx scripts/bootstrap-obo-conformance-fixture.ts \
 *     --secret-bundle /path/to/.secrets.obo.json --print-manifest
 *
 * Secret bundle format (generated by the harness):
 *   { "callerASecret": "…", "callerBSecret": "…", "adcProxySecret": "…" }
 *
 * Security guarantees:
 *   - Secrets are NEVER written to stdout or logs
 *   - stdout JSON manifest contains only SHA-256 digests of secrets
 *   - All records use upsert for idempotency
 *   - The same secret bundle always produces the same database state
 */


// ---------------------------------------------------------------------------
// Contract-derived audience scopes (read from runtime, not hardcoded)
// ---------------------------------------------------------------------------

function requiredAudience(audienceId: string) {
  const def = getV1AudienceDefinitions().find((a) => a.audienceId === audienceId);
  if (!def) {
    throw new Error(
      `Frozen contract does not define audience "${audienceId}". ` +
      `Cannot bootstrap fixture.`,
    );
  }
  return def;
}

function validateContractFacts(): void {
  const svcWorkflow = requiredAudience('svc-workflow');
  const adcV2 = requiredAudience('adc-v2');

  // svc-workflow: must support delegated access for agents
  if (!svcWorkflow.delegatedAccessEnabled) {
    throw new Error('svc-workflow must have delegatedAccessEnabled=true in frozen contract.');
  }
  if (!svcWorkflow.acceptedPrincipalTypes.includes('agent')) {
    throw new Error('svc-workflow must accept agent principal type in frozen contract.');
  }
  if (!svcWorkflow.registeredScopes.includes('workflow.read')) {
    throw new Error('svc-workflow must register workflow.read scope.');
  }
  if (!svcWorkflow.registeredScopes.includes('workflow.execute')) {
    throw new Error('svc-workflow must register workflow.execute scope.');
  }

  // adc-v2: must support machine access for agents
  if (!adcV2.machineAccessEnabled) {
    throw new Error('adc-v2 must have machineAccessEnabled=true in frozen contract.');
  }
  if (!adcV2.acceptedPrincipalTypes.includes('agent')) {
    throw new Error('adc-v2 must accept agent principal type in frozen contract.');
  }
  if (!adcV2.registeredScopes.includes('adc.read')) {
    throw new Error('adc-v2 must register adc.read scope.');
  }
}

// ---------------------------------------------------------------------------
// Secret bundle
// ---------------------------------------------------------------------------

interface SecretBundle {
  callerASecret: string;
  callerBSecret: string;
  adcProxySecret: string;
}

function loadSecretBundle(path: string): SecretBundle {
  const raw = fs.readFileSync(path, 'utf8');
  const parsed = JSON.parse(raw) as Record<string, unknown>;
  for (const key of ['callerASecret', 'callerBSecret', 'adcProxySecret']) {
    if (typeof parsed[key] !== 'string' || (parsed[key] as string).length < 16) {
      throw new Error(`Secret bundle missing or invalid field: ${key}`);
    }
  }
  return parsed as SecretBundle;
}

function sha256(value: string): string {
  return crypto.createHash('sha256').update(value).digest('hex');
}

// ---------------------------------------------------------------------------
// Manifest shape (no plaintext secrets)
// ---------------------------------------------------------------------------

interface FixtureManifest {
  contractVersion: string;
  audiences: Array<{ audienceId: string; status: string; scopes: string[] }>;
  principals: Record<string, { id: string; type: string; agentId: string | null }>;
  clients: Record<string, { clientId: string; principalId: string }>;
  trustedProxy: { id: string; proxyPrincipalId: string; proxyClientId: string } | null;
  delegationGrants: Array<{ audienceId: string; scopes: string[] }>;
  acceptedSubjectAudiences: string[];
  // Negative test fixtures
  misMatchProxy: { principalId: string; clientId: string } | null;
  noTpProxy: { principalId: string; clientId: string } | null;
  disabledProxy: { principalId: string; clientId: string } | null;
  noDgProxy: { principalId: string; clientId: string } | null;
  callerC: { principalId: string; clientId: string; agentId: string } | null;
  // Only SHA-256 digests, never plaintext
  secretDigests: Record<string, string>;
}

